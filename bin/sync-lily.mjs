#!/usr/bin/env node
// Vendor the Lily Design System pieces this site uses.
//
// Lily's Svelte headless components and helpers are MIT licensed. The helpers
// are not published to npm at the version this site tracks, and the local
// checkout runs ahead of what is published, so the site vendors both from
// the sibling checkout and records the source commit in src/lib/lily/VENDOR.md.
//
// Source: $LILY if set, else ~/git/lilydesignsystem/lily-design-system.
// Run after Lily changes:  npm run sync:lily

import { cp, mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lily = resolve(process.env.LILY ?? join(homedir(), 'git', 'lilydesignsystem', 'lily-design-system'));

const headless = join(lily, 'lily-design-system-svelte-headless', 'components');
const helpers = join(lily, 'lily-design-system-svelte-helpers');
const themes = join(lily, 'themes');

if (!existsSync(headless)) {
	console.error(`No Lily checkout at ${lily}. Set LILY=/path/to/lily-design-system.`);
	process.exit(1);
}

// Only the components the site actually renders. Add to this list rather than
// copying all 492 — every vendored file is code this repo now carries.
const components = [
	'SkipLink',
	'Header',
	'Footer',
	'ArticleLayout',
	'ContentsNav',
	'ContentsList',
	'ContentsListItem',
	'BreadcrumbNav',
	'BreadcrumbList',
	'BreadcrumbListItem',
	'PaginationNav',
	'PaginationList',
	'PaginationListItem',
	// Needed by the vendored picker helpers below (their own source imports
	// these from "@lilydesignsystem/svelte-headless" — see the matching
	// generated barrel and vite.config.js alias).
	'IconButton',
	'Listbox'
];

/**
 * Helper packages the header's PickerBar needs: source directory name ->
 * files to copy verbatim (component(s), the real index.ts barrel, and any
 * same-directory sibling the component itself imports). Vendored into its
 * own subdirectory per package, mirroring the real npm package layout, so
 * vite.config.js can alias the bare "@lilydesignsystem/…" specifiers
 * picker-bar's own source imports straight at these barrels — no source
 * editing, no duplicated re-export code to keep in sync by hand.
 */
const helperPackages = [
	['lily-design-system-svelte-theme-picker', 'theme-picker', ['ThemePicker.svelte', 'index.ts']],
	[
		'lily-design-system-svelte-locale-picker',
		'locale-picker',
		['LocalePicker.svelte', 'locales.ts', 'index.ts']
	],
	[
		'lily-design-system-svelte-text-size-picker',
		'text-size-picker',
		['TextSizePicker.svelte', 'index.ts']
	],
	['lily-design-system-svelte-share-picker', 'share-picker', ['SharePicker.svelte', 'index.ts']],
	['lily-design-system-svelte-picker-bar', 'picker-bar', ['PickerBar.svelte', 'index.ts']]
];

const lilyDir = join(siteRoot, 'src', 'lib', 'lily');
await rm(lilyDir, { recursive: true, force: true });
await mkdir(join(lilyDir, 'components'), { recursive: true });
await mkdir(join(lilyDir, 'helpers'), { recursive: true });

for (const name of components) {
	const from = join(headless, name, `${name}.svelte`);
	if (!existsSync(from)) {
		console.error(`missing component: ${name}`);
		process.exit(1);
	}
	await cp(from, join(lilyDir, 'components', `${name}.svelte`));
}

// The picker helpers import IconButton/Listbox from the published
// "@lilydesignsystem/svelte-headless" package barrel. This site vendors
// headless components individually (flat files in components/, not a
// package), so generate the matching barrel and alias the bare specifier
// at it in vite.config.js.
await writeFile(
	join(lilyDir, 'headless-for-helpers.js'),
	`// Generated by bin/sync-lily.mjs — a barrel matching the real
// "@lilydesignsystem/svelte-headless" package's exports, for the vendored
// picker helpers (src/lib/lily/helpers/*) to import from. Do not edit by
// hand; re-run \`npm run sync:lily\`.
export { default as IconButton } from './components/IconButton.svelte';
export { default as Listbox } from './components/Listbox.svelte';
`
);

let helperFileCount = 0;
for (const [pkg, dir, files] of helperPackages) {
	const from = join(helpers, pkg);
	const to = join(lilyDir, 'helpers', dir);
	await mkdir(to, { recursive: true });
	for (const file of files) {
		const src = join(from, file);
		if (!existsSync(src)) {
			console.error(`missing helper file: ${pkg}/${file}`);
			process.exit(1);
		}
		await cp(src, join(to, file));
		helperFileCount += 1;
	}
}

// Themes: light and dark, plus the UK health and government themes, which are
// the ones a reader of this book is most likely to want.
const themeDir = join(siteRoot, 'static', 'themes');
await rm(themeDir, { recursive: true, force: true });
await mkdir(themeDir, { recursive: true });
const wanted = (name) =>
	['light.css', 'dark.css'].includes(name) || name.startsWith('united-kingdom-');
const themeFiles = (await readdir(themes)).filter((n) => n.endsWith('.css') && wanted(n)).sort();
for (const name of themeFiles) {
	await cp(join(themes, name), join(themeDir, name));
}

let commit = 'unknown';
try {
	commit = execFileSync('git', ['-C', lily, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
} catch {
	// A tarball checkout has no git metadata; provenance is best-effort.
}

await writeFile(
	join(lilyDir, 'VENDOR.md'),
	`# Vendored Lily Design System

These files are copied verbatim from the Lily Design System (MIT licence) by
\`bin/sync-lily.mjs\`. Do not edit them here — change them upstream and re-run
\`npm run sync:lily\`.

- Source: <https://github.com/LilyDesignSystem>
- Commit: \`${commit}\`
- Components: ${components.join(', ')}
- Helper packages (each in its own \`helpers/<name>/\`, verbatim including its
  real \`index.ts\` barrel): ${helperPackages.map(([, dir]) => dir).join(', ')}
- \`picker-bar\`'s own source imports its four wrapped pickers, and each of
  those imports \`IconButton\`/\`Listbox\` from \`@lilydesignsystem/svelte-headless\`,
  as real package specifiers, unmodified — see the matching aliases in
  \`vite.config.js\`, which point those specifiers at the vendored barrels
  above (including the generated \`headless-for-helpers.js\`) instead of a
  real npm install.
- Themes: \`static/themes/\` (${themeFiles.length} files)
`
);

console.log(
	`Vendored ${components.length} components, ${helperPackages.length} helper packages (${helperFileCount} files), ${themeFiles.length} themes from ${lily} (${commit.slice(0, 9)}).`
);
